import { readFile } from "node:fs/promises";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const schemaUrl = new URL("../schemas/wayfinder-document.v4.schema.json", import.meta.url);

export const generatedValidatorUrl = new URL(
  "../app/wayfinder-schema-validator.generated.mjs",
  import.meta.url,
);

function inlineUnicodeLengthHelper(source) {
  const inlined = source.replace(
    /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
    (_match, name) => `function ${name}(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  while (pos < len) {
    length += 1;
    const value = str.charCodeAt(pos);
    if (value >= 0xd800 && value <= 0xdbff && pos + 1 < len) {
      const extra = str.charCodeAt(pos + 1);
      if ((extra & 0xfc00) === 0xdc00) pos += 1;
    }
    pos += 1;
  }
  return length;
}`,
  );
  if (/require\(|ajv\/dist\/runtime|new Function|\beval\s*\(/.test(inlined)) {
    throw new Error("Standalone validator still depends on an Ajv runtime helper.");
  }
  return inlined;
}

export async function createSchemaValidatorSource() {
  const schema = JSON.parse(await readFile(schemaUrl, "utf8"));
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    code: { esm: true, lines: true, source: true },
  });
  const validate = ajv.compile(schema);
  const source = [
    "// Generated by scripts/generate-schema-validator.mjs. DO NOT EDIT.",
    "// Regenerate with: npm run generate:schema-validator",
    inlineUnicodeLengthHelper(standaloneCode(ajv, validate)).trimEnd(),
  ].join("\n");
  return `${source}\n`;
}
